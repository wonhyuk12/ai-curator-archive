export type Pricing = "Free" | "Freemium" | "Paid";

export interface ToolInfo {
  name: string;
  description: string;
  pricing: Pricing;
  url: string;
  /** TOOLS 키 목록 */
  related: ToolKey[];
  /** 왜 좋은가 */
  strengths: string[];
  /** 이렇게 활용하세요 (단계) */
  howTo: string[];
}

export interface ToolEntry {
  tool: ToolKey;
  /** 한 줄 용도 — 노드 카드에 표시 */
  useCase: string;
  tag: string;
  /** 이 작업에 추천하는 이유 (툴 패널 맨 위) */
  recommendation: string;
  /** 이 작업에 바로 쓸 수 있는 예시 프롬프트 (프롬프트 입력이 없는 툴은 생략) */
  prompt?: string;
}

export interface SubField {
  id: string;
  name: string;
  nameEn: string;
  /** 이 분야에서 AI로 할 수 있는 일 — 마인드맵 노드에 한 줄로 표시 */
  desc: string;
  icon: LucideIcon;
  tools: ToolEntry[];
}

export type TaskGroup = "work" | "create" | "life";
